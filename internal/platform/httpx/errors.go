package httpx

import (
	"errors"
	"log/slog"
	"net/http"

	"github.com/gin-gonic/gin"

	"github.com/damchi/sport-challenge-api/internal/platform/apperr"
)

type errorResponse struct {
	Error errorBody `json:"error"`
}

type errorBody struct {
	Code      apperr.Code       `json:"code"`
	Message   string            `json:"message"`
	Params    map[string]string `json:"params,omitempty"`
	RequestID string            `json:"request_id,omitempty"`
}

// RespondError is the only place that turns an error into a response, in the
// single format of the API: {"error": {"code", "message", "params",
// "request_id"}}. An *apperr.Error gives its code, status, fallback message
// and parameters, never its cause. Any other error answers a generic 500
// internal_error. Every 5xx with a cause is logged with it (the only trace of
// a technical failure); 4xx are not. If the response has already started, it
// only logs, so the body is never corrupted by a second document.
func RespondError(c *gin.Context, logger *slog.Logger, err error) {
	var appErr *apperr.Error
	if !errors.As(err, &appErr) {
		appErr = apperr.New(apperr.CodeInternal, err)
	}
	// A 5xx without cause (Recovery logs the panic itself) has nothing to add.
	if appErr.Status >= http.StatusInternalServerError && errors.Unwrap(appErr) != nil {
		logger.ErrorContext(c.Request.Context(), "request failed",
			slog.String("route", c.FullPath()),
			slog.String("request_id", RequestID(c)),
			slog.String("code", string(appErr.Code)),
			slog.String("error", err.Error()),
		)
	}
	if c.Writer.Written() {
		c.Abort()
		return
	}
	c.AbortWithStatusJSON(appErr.Status, errorResponse{Error: errorBody{
		Code:      appErr.Code,
		Message:   appErr.Message,
		Params:    appErr.Params,
		RequestID: RequestID(c),
	}})
}

// ErrorHandler adapts RespondError to the handlers generated by oapi-codegen
// (handler and response errors).
func ErrorHandler(logger *slog.Logger) func(*gin.Context, error) {
	return func(c *gin.Context, err error) {
		RespondError(c, logger, err)
	}
}

// InvalidParamHandler answers validation_failed when the generated router
// rejects a path, query or header parameter. The binding error, which may
// echo the client's value, is not sent back.
func InvalidParamHandler(logger *slog.Logger) func(*gin.Context, error, int) {
	return func(c *gin.Context, err error, _ int) {
		RespondError(c, logger, apperr.New(apperr.CodeValidationFailed, err))
	}
}

// BadRequestHandler answers validation_failed when a request body cannot be
// decoded. The decoding error is not echoed back.
func BadRequestHandler(logger *slog.Logger) func(*gin.Context, error) {
	return func(c *gin.Context, err error) {
		RespondError(c, logger, apperr.New(apperr.CodeValidationFailed, err))
	}
}
